export function translate(lang: Lang, k: string, v?: Record<string, string | number>) {
  let s =
    EXTRA[lang][k] ??
    I18N[lang][k] ??
    EXTRA.en[k] ??
    I18N.en[k] ??
    (k.includes("_") ? k.split("_").slice(1).join("_") : k);
  if (v) for (const [a, b] of Object.entries(v)) s = s.replaceAll(`{${a}}`, String(b));
  return s;
}

export const locale = (lang: Lang) => (lang === "ar" ? "ar-EG-u-nu-latn" : "en-GB");
export const fmt = (v: number | null | undefined, d = 1) =>
  v == null || Number.isNaN(v) ? "—" : Number(v).toLocaleString("en-US", { maximumFractionDigits: d });
export const fmtDay = (lang: Lang, iso?: string | null) =>
  iso
    ? new Date(iso.length === 10 ? iso + "T00:00" : iso).toLocaleDateString(locale(lang), {
        day: "numeric",
        month: "short",
      year: "numeric",
      })
    : "—";
export const fmtWhen = (lang: Lang, iso?: string | null) =>
  iso
    ? new Date(iso).toLocaleString(locale(lang), {
        day: "numeric",
        month: "short",
        year: "numeric",
        hour: "2-digit",
        minute: "2-digit",
        hourCycle: "h23",
      })
    : "—";
